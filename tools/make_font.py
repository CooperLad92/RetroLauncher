def gname(ch):
    return 'space' if ch == ' ' else 'uni%04X' % ord(ch)

def draw(rows, pen):
    for r, line in enumerate(rows):
        y_top = (7 - r) * PX           # row 0 sits 7 px above baseline
        c = 0
        while c < 5:
            if line[c] == '#':
                s = c
                while c < 5 and line[c] == '#':
                    c += 1
                x0, x1 = s * PX, c * PX
                y0, y1 = y_top - PX - 2, y_top + 2   # tiny overlap -> no seams
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            else:
                c += 1

order = ['.notdef'] + [gname(ch) for ch in G] + ['uni2588']
glyphs, metrics, cmap = {}, {}, {}
pen = TTGlyphPen(None)
glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (ADV, 0)
for ch, spec in G.items():
    p = TTGlyphPen(None); draw(spec.split('|'), p)
    n = gname(ch); glyphs[n] = p.glyph(); metrics[n] = (ADV, 0)
    cmap[ord(ch)] = n
    if 'A' <= ch <= 'Z':
        cmap[ord(ch.lower())] = n
# full block (cursor)
p = TTGlyphPen(None)
p.moveTo((0, -2 * PX)); p.lineTo((0, 8 * PX)); p.lineTo((ADV, 8 * PX)); p.lineTo((ADV, -2 * PX)); p.closePath()
glyphs['uni2588'] = p.glyph(); metrics['uni2588'] = (ADV, 0); cmap[0x2588] = 'uni2588'

fb = FontBuilder(8 * PX, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=9 * PX, descent=-3 * PX)
fb.setupNameTable({'familyName': 'Retro Pixel', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=9 * PX, sTypoDescender=-3 * PX, usWinAscent=9 * PX, usWinDescent=3 * PX)
fb.setupPost(isFixedPitch=1)
fb.save(sys.argv[1])
